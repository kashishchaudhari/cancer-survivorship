// The coverage lens uses the same descriptive filters as the cohort charts.
async function initializeCoverageLens() {
  const cube = await load('raw_zip_full_eda_cube.csv');
  function render() {
    const filters = {source_cohort: 'cohort', age_band: 'age', sex: 'sex', race: 'race', diagnosis_decade: 'decade'};
    const rows = cube.filter(row => Object.entries(filters).every(([field, id]) => document.getElementById(id).value === 'All' || row[field] === document.getElementById(id).value));
    const sites = [...new Set(cube.map(row => row.source_cohort))].sort();
    const ages = ['Under 40', '40-64', '65+', 'Unknown'].filter(age => cube.some(row => row.age_band === age));
    const measure = document.getElementById('matrix-metric').value;
    const cells = sites.map(site => ages.map(age => {
      const group = rows.filter(row => row.source_cohort === site && row.age_band === age);
      const total = group.reduce((sum, row) => sum + Number(row.patient_count), 0);
      const known = group.filter(row => row.outcome_state !== 'Outcome unavailable').reduce((sum, row) => sum + Number(row.patient_count), 0);
      const events = group.filter(row => row.outcome_state === 'Suicide outcome recorded').reduce((sum, row) => sum + Number(row.patient_count), 0);
      return {total, known, events, value: measure === 'coverage' ? (total ? 100 * known / total : null) : (known ? 100 * events / known : null)};
    }));
    Plotly.react('coverage-matrix', [{type:'heatmap', x:ages, y:sites, z:cells.map(row => row.map(cell => cell.value)),
      customdata:cells.map(row => row.map(cell => [cell.total, cell.known, cell.events, cell.known && cell.events < 11 ? 'Sparse event group: interpret cautiously' : 'Descriptive group'])),
      colorscale:measure === 'coverage' ? [[0,'#edf2f4'],[.5,'#7ac3bc'],[1,'#126d69']] : [[0,'#f5ede3'],[.5,'#d8a367'],[1,'#904747']],
      zmin:0, ...(measure === 'coverage' ? {zmax:100} : {}), hoverongaps:false,
      colorbar:{title:measure === 'coverage' ? 'Coverage %' : 'Fraction %',thickness:12},
      hovertemplate:'%{y} · %{x}<br>Measure: %{z:.2f}%<br>Index patients: %{customdata[0]:,}<br>Known outcomes: %{customdata[1]:,}<br>Recorded events: %{customdata[2]:,}<br>%{customdata[3]}<extra></extra>'}],
      {margin:{t:15,r:35,b:45,l:85},paper_bgcolor:'transparent',plot_bgcolor:'transparent',font:{family:'Segoe UI, sans-serif',color:'#112433'},xaxis:{title:'Age at index diagnosis'},yaxis:{autorange:'reversed'}},
      {responsive:true,displayModeBar:false});
    const total = rows.reduce((sum,row)=>sum+Number(row.patient_count),0);
    document.getElementById('matrix-insight').textContent = total ? (measure === 'coverage' ? 'Light cells identify incomplete outcome coverage. Blank cells have no patients under the selected filters.' : 'Fraction = recorded suicide outcomes / patients with known outcomes. Blank cells have no known outcomes; sparse event groups are flagged in tooltips. These are supplied-data descriptions, not population risk estimates.') : 'No index patients match these filters. Reset filters to restore the full descriptive cohort.';
  }
  for (const id of ['cohort','age','sex','race','decade','matrix-metric']) document.getElementById(id).addEventListener('change', render);
  document.getElementById('reset').addEventListener('click', () => setTimeout(render,0));
  render();
}
initializeCoverageLens().catch(error => {document.getElementById('matrix-insight').textContent = error.message;});

// Display release evidence generated by the validated build.
(async () => {
  try {
    const response = await fetch('data/manifest.json');
    if (!response.ok) throw new Error('Run the validated build to generate release evidence.');
    const manifest = await response.json();
    document.getElementById('data-classification').textContent = manifest.confidentiality || 'Confidential local research data';
    document.querySelector('.badge').textContent = manifest.synthetic ? 'SYNTHETIC TEST DATA' : 'CONFIDENTIAL · LOCAL RESEARCH';
    document.getElementById('release-status').textContent = manifest.status === 'passed' ? 'All aggregate contracts passed' : manifest.status;
    document.getElementById('release-time').textContent = new Date(manifest.built_at_utc).toLocaleString();
    document.getElementById('release-revision').textContent = manifest.revision === 'local' ? 'Local preview · not deployed' : manifest.revision.slice(0, 12);
    document.getElementById('release-checks').textContent = `${manifest.checks.length} checks · ${manifest.tables.length} datasets`;
    for (const check of manifest.checks) {
      const item = document.createElement('li');
      item.textContent = check;
      document.getElementById('quality-checks').append(item);
    }
    for (const table of manifest.tables) {
      const row = document.createElement('tr');
      for (const text of [table.name, table.rows.toLocaleString(), table.population, table.sha256.slice(0, 16) + '…']) {
        const cell = document.createElement('td');
        cell.textContent = text;
        row.append(cell);
      }
      row.lastChild.title = table.sha256;
      document.getElementById('lineage-body').append(row);
    }
  } catch (error) {
    document.getElementById('release-status').textContent = error.message;
  }
})();
